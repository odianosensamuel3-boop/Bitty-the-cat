/** True when the tokenomics split is complete, valid and ready to render. */
export function isTokenomicsReady(): boolean {
  const { allocations, finalized } = siteConfig.tokenomics;
  if (!finalized) return false;
  if (allocations.length === 0) return false;
  const total = allocations.reduce((sum, a) => sum + (typeof a.percent === "number" ? a.percent : 0), 0);
  const allSet = allocations.every((a) => typeof a.percent === "number" && a.percent > 0);
  return allSet && Math.round(total * 100) / 100 === 100;
}

/** Verified total supply as a BigInt, or null. */
export function getTotalSupply(): bigint | null {
  const raw = siteConfig.token.totalSupply;
  if (!isSet(raw)) return null;
  try {
    return BigInt(raw.replace(/[^0-9]/g, ""));
  } catch {
    return null;
  }
}

/** Human readable supply, e.g. "1,000,000,000 tokens". */
export function formatTotalSupply(): string {
  const supply = getTotalSupply();
  if (supply === null) return NOT_AVAILABLE;
  return `${supply.toLocaleString("en-US")} ${siteConfig.token.totalSupplyUnit}`;
}

/** Absolute amount of an allocation, e.g. "250,000,000". */
