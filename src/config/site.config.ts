/** Shown wherever an official value has not been published yet. */
export const NOT_AVAILABLE = "Not yet available";
export const COMING_SOON = "Coming soon";

/** True when a config string holds a real (non-empty) value. */
export function isSet(value: unknown): value is string {
  return typeof value === "string" && value.trim().length > 0;
}

/** Returns the value, or a friendly placeholder when it is not configured. */
export function displayValue(value: unknown, fallback: string = NOT_AVAILABLE): string {
  return isSet(value) ? value.trim() : fallback;
}

/**
 * Only accepts absolute https URLs. Anything else (empty, "#", "TODO", http,
 * javascript:, relative paths) is treated as "not configured" so a button can
 * never point at a fake or insecure destination.
 */
export function safeExternalUrl(value: unknown): string | null {
  if (!isSet(value)) return null;
  try {
    const url = new URL(value.trim());
    if (url.protocol !== "https:") return null;
    if (!url.hostname.includes(".")) return null;
    return url.toString();
  } catch {
    return null;
  }
}

